// Regenerated on every `pnpm build`/`pnpm start` (see prebuild/prestart in
// package.json) from docs/changelog.md, which release.yml updates on every
// version tag. Keeps the homepage changelog from going stale like the old
// hand-maintained array did.
const fs = require('fs')
const path = require('path')

const SOURCE = path.join(__dirname, '..', 'docs', 'changelog.md')
const OUTPUT = path.join(__dirname, '..', 'src', 'data', 'homeChangelog.generated.ts')
const MAX_RELEASES = 5

function stripMarkdown(line) {
  return line
    .replace(/\*\*(.*?)\*\*/g, '$1')
    .replace(/\[([^\]]+)\]\(([^)]+)\)/g, '$1 ($2)')
    .replace(/^[*-]\s+/, '')
    .trim()
}

function parseChangelog(markdown) {
  const start = markdown.indexOf('<!-- changelog:start -->')
  const end = markdown.indexOf('<!-- changelog:end -->')
  const body = start !== -1 && end !== -1 ? markdown.slice(start, end) : markdown

  const lines = body.split('\n')
  const releases = []
  let current = null

  for (const rawLine of lines) {
    const heading = rawLine.match(/^##\s+v?([\d.]+)\s*-\s*(.+)$/)
    if (heading) {
      current = { version: heading[1], date: heading[2].trim(), changes: [] }
      releases.push(current)
      continue
    }
    if (!current) continue
    const text = stripMarkdown(rawLine)
    if (text) current.changes.push(text)
  }

  return releases.slice(0, MAX_RELEASES)
}

const markdown = fs.readFileSync(SOURCE, 'utf8')
const releases = parseChangelog(markdown)

const contents = `// Auto-generated by scripts/generate-home-changelog.js — do not edit by hand.
export type Release = {
  version: string
  date: string
  changes: string[]
}

export const releases: Release[] = ${JSON.stringify(releases, null, 2)}
`

fs.mkdirSync(path.dirname(OUTPUT), { recursive: true })
fs.writeFileSync(OUTPUT, contents)
console.log(`Generated ${OUTPUT} with ${releases.length} release(s).`)
